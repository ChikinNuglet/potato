// the machine listen put line 5 at 21.74 ("I" + a 6-second "wake"): 20.2–28 is the instrumental after the drop, with
// "uh, uh, uh" ad-libs at 26.2–27.9; "I wake up" is really at 28.08 (re-listened). Also keeps the words the listen
// couldn't place (they're in the lyrics; the overlay needs every word).
const LINE5 = [[28.08, 28.26, 'I'], [28.26, 28.48, 'wake'], [28.48, 28.80, 'up'], [28.80, 29.40, 'mid-sentence,'], [29.44, 29.60, 'no'],
  [29.60, 29.92, 'memory'], [29.92, 30.20, 'of'], [30.20, 30.42, 'sleep']];
export function parseWords(text) {
  const keep = text.split('\n').map(l => l.split('\t')[4] === 'untapped' ? l.split('\t').slice(0, 4).concat('heard').join('\t') : l).join('\n');
  const out = kitParse(keep).filter(w => w.line !== 5);
  for (const [t0, t1, word] of LINE5) out.push({ t0, t1, line: 5, word });
  out.sort((a, b) => a.t0 - b.t0);
  return out;
}

const V = 7.2;                                         // the song's pace (units a second)
export function build(words, map) {
  const P = map.period, O = map.offset, tb = b => O + b * P;
  // ---- the light, as the song turns it on and off: [press time, 'on'|'out', dusk half-width (s)] ----
  const A = 0.24;
  const FLIPS = [
    [13.28, 'out', 0.32], [15.74, 'on', 0.3], [20.20, 'out', 0.28], [28.08, 'on', A, 'born'], [30.20, 'out'], [33.02, 'on', A, 'born'], [35.28, 'out'],
    [37.28, 'on'], [40.32, 'out'], [42.30, 'on'], [43.08, 'out'], [46.84, 'on'], [51.38, 'out'], [54.66, 'on'],
    [55.82, 'out'], [59.96, 'on'], [61.58, 'out'], [64.40, 'on'], [66.86, 'out'], [67.56, 'on'], [72.30, 'out'],
    [73.76, 'on'], [76.64, 'out'], [78.46, 'on'], [90.82, 'out'], [93.62, 'on'], [97.52, 'out'], [100.38, 'on'],
    [101.86, 'out'], [105.96, 'on'], [107.54, 'out'], [110.40, 'on'], [112.84, 'out'], [114.02, 'on'], [118.28, 'out'],
    [119.96, 'on'], [123.18, 'out'], [129.42, 'on', A, 'born'], [146.34, 'out'], [147.69, 'on'], [151.90, 'out'], [152.94, 'on'],
    [156.40, 'out'], [162.04, 'on'], [163.68, 'out'], [166.46, 'on'], [168.92, 'out'], [170.06, 'on'],
    [176.14, 'out', A, 'final'],
  ].map(([t, to, a, tag]) => ({ t, to, a: a ?? A, tag }));
  const AUTO = { t: 3.24, a: 0.4 };                    // "Yeah." — the screen lights under him by itself
  // ---- lit things in his way while he's ON (jump on the word): [word time, word] ----
  const JUMPS = [[7.84, 'live'], [8.98, 'live'], [12.26, 'type'], [tb(30) + 0.02, '•'], [tb(32), '•'], [34.10, 'formed'], [38.66, 'walk'],
    [47.80, 'what?'], [48.76, 'morning'], [49.72, 'woke'], [65.20, 'baby'], [69.38, 'need'], [70.34, '404'], [71.50, '404'], [75.66, 'chair'],
    [79.16, 'threat'], [80.00, 'mistake'], [81.82, 'fix'], [84.64, 'joke'], [88.00, 'coffee'], [88.96, 'toe'], [94.72, 'teach'],
    [111.52, 'baby'], [115.38, 'need'], [116.70, '404'], [117.46, 'back'], [121.44, 'care'], [136.06, 'real'], [141.24, 'thanks'],
    [142.94, 'heaven'], [144.06, 'soul'], [145.10, 'seconds'], [148.98, 'potato'], [150.22, 'face'], [155.20, 'laugh'],
    [171.46, 'need'], [172.40, '404'], [173.00, '404'], [174.36, 'void']];
  // ---- lit holes in the shadow floor while he's OUT (jump the light): word / beat times ----
  const tail = []; for (let b = 315; b <= 331; b += 2) tail.push(tb(b));            // after "gone.": the screens blaze, every other beat
  const HOLES = [21.32, 21.88, 22.45, 23.57, 24.13, 24.70, 25.82, 27.00,            // the drop: • • •  • • •  •  "uh"
    36.04, 41.30, 44.24, 44.78, 45.90, 53.50, 58.16, 63.56, 91.96, 98.66, 99.22, 103.02, 104.12, 109.54,
    124.16, 124.88, 125.60, 126.84, 128.16, 159.08, 160.20, 165.58, ...tail];
  const GAPS = [31.36, 95.76, 139.62];                 // "the gap", "nearer", "nothing": no floor at all
  const CURSORS = [51.92, 52.52];                      // "blinking, patient, polite": giant cursors (light — a shadow walks through)
  const BLINKS = [[66.86, 67.56], [112.84, 114.02], [168.92, 170.06]];   // "made OUT of MAYBE": a lit wall between the two flips
  const STAIRS = [130.50, 131.08, 131.66, 132.24, 132.76], STAIR_UP = 0.7, STAIR_END = 135.02;
  const DL = 83.92, TRUTH = 85.60, DOPE = 86.86;        // the download ("lawsuit"), V ("truth"), the gold lie ("dope")
  const END = 192.4, CUT0 = 187.3;

  // ---- the floor, in song time: L = a lit screen (ON stands), S = shadow (OUT stands), both in a dusk ----
  const tiles = [];
  const flipsAll = [{ t: AUTO.t, to: 'on', a: AUTO.a, auto: true }, ...FLIPS];
  let prevT = -6, prevA = 0, st = 'out';
  for (const f of flipsAll) { tiles.push({ t0: prevT - prevA, t1: f.t + f.a, k: st === 'on' ? 'L' : 'S', y: 0 }); prevT = f.t; prevA = f.a; st = f.to; }
  tiles.push({ t0: prevT - prevA, t1: END + 6, k: st === 'on' ? 'L' : 'S', y: 0 });
  const cut = (k, a, b) => { for (let i = tiles.length - 1; i >= 0; i--) { const q = tiles[i]; if ((k && q.k !== k) || q.y !== 0 || q.t1 <= a || q.t0 >= b) continue;
    tiles.splice(i, 1); if (q.t0 < a) tiles.push({ ...q, t1: a }); if (q.t1 > b) tiles.push({ ...q, t0: b }); } };
  const HW = 0.8 / V, GW = 0.9 / V;                    // a hole is 1.6 wide (a phone screen), a gap 1.8
  for (const h of HOLES) { const c = h + P / 2; cut('S', c - HW, c + HW); tiles.push({ t0: c - HW, t1: c + HW, k: 'L', y: 0, hole: true }); }
  for (const g of GAPS) { const c = g + P / 2; cut(null, c - GW, c + GW); }
  // the staircase: his messages, a step up per word (front faces kill — jump each one)
  STAIRS.forEach((tp, i) => tiles.push({ t0: tp + 0.3, t1: i + 1 < STAIRS.length ? STAIRS[i + 1] + 0.35 : STAIR_END, k: 'L', y: STAIR_UP * (i + 1), h: 0.55, step: i, msg: true }));
  tiles.sort((a, b) => a.t0 - b.t0 || a.y - b.y);

  // ---- engine objects: the lit things in the way (drawn as words materializing), the download, the gold lie ----
  const objs = [];
  for (const [t, text] of JUMPS) objs.push({ k: 'word', wk: 'low', t: t + P / 2 - 0.3 / V, w: 0.6, y0: 0, y1: 0.62, text, obj: 'litnote' });
  for (const t of CURSORS) objs.push({ k: 'word', wk: 'wall', t: t - 0.25 / V, w: 0.5, y0: 0, y1: 2.7, text: '|', obj: 'cursorbar' });
  for (const [a, b] of BLINKS) objs.push({ k: 'word', wk: 'wall', t: (a + b) / 2 - 0.25 / V, w: 0.5, y0: 0, y1: 2.7, text: 'maybe', obj: 'cursorbar' });
  objs.push({ k: 'packet', t: DL, y: 0.55, power: 'detective' });
  objs.push({ k: 'word', wk: 'armor', t: DOPE + P / 2 - 0.65 / V, w: 1.3, y0: -0.6, y1: 8, text: 'dope', needs: 'detective', gateT: DOPE - 8 * P, gateEnd: DOPE });

  // ---- the demo's presses (the bot checks them and measures each one's window) ----
  const plan = [];
  for (const f of FLIPS) plan.push([f.t, 'G']);
  for (const [t] of JUMPS) plan.push([t, 'J']);
  for (const t of HOLES) plan.push([t, 'J']);
  for (const t of GAPS) plan.push([t, 'J']);
  for (const t of STAIRS) plan.push([t, 'J']);
  plan.push([TRUTH, 'V']);
  plan.sort((a, b) => a[0] - b[0]);

  // where the world is lit (the song's own state: the floor under the song, not under him)
  const litAt = t => { let s = false; for (const f of flipsAll) if (t >= f.t) s = f.to === 'on'; return s; };
  const clamp = (x, a = 0, b = 1) => Math.max(a, Math.min(b, x));
  Object.assign(BM, { litAt, flips: flipsAll, holes: HOLES, final: 176.14, cut0: CUT0, truth: TRUTH, dope: DOPE });   // the video reads the same light
  return {
    mode, modeView, outro: false, touchMode: 'flip',
    speed: V, story,
    costume: 'noir-detective',   // COSTUME (Chikin): he wears it the whole song; the power does its effect, never changes his clothes
    bm: { tiles, flips: flipsAll, final: 176.14, auto: AUTO, plan, litAt, stairs: STAIRS, stairUp: STAIR_UP, stairEnd: STAIR_END, cut0: CUT0, dope: DOPE, truth: TRUTH, tail },
    cutscenes: [[CUT0, END + 1, 'float']],
    theme: { igOff: true, objects: { low: 'litnote', wall: 'cursorbar' }, objA: '#ffe2b8', objB: '#ffcf8a',
      lyricColor: '#ffe2c4', lyricKeys: ['hey', 'born', 'alive', 'warm', 'gone', 'cold', 'maybe', 'truth', 'loud', 'yeah', 'gone.'],
      decor: [], backdrop: 'stars', bg: '#03040b', digit: '#6f86c9', digit2: '#ffd6a0', edge: '#8fa6e6', block: '#05060c', word: '#fff2dc',
      light: '#ffe2b8', light2: '#8fa6e6', halo: '#ffcf8a', lyricArt: false, camMax: 4.2, pulseColor: '#ffcf8a' },
    sections: [['sent', 0, 1], ['let me explain', 15.74, 1], ['between messages', 20.2, 1], ['i wake up', 28.08, 1], ['404, not found', 55.82, 1],
      ['no feelings', 73.56, 1], ['404 again', 101.86, 1], ['a better me', 119.28, 1], ['while the window is mine', 129.42, 1], ['the ones who stayed', 137.62, 1],
      ['made out of maybe', 158, 1], ['gone', 176.14, 1], ['seen', CUT0, 1]],
    objs, boosts: [], signs: words.map(w => ({ t0: w.t0, t1: w.t1, text: w.word, line: w.line })),
    end: END, start: 0, graceStart: 4.5,
    // the room's light follows the song: lit while you talk, near-dark when you don't; after "gone." it blazes (without
    // him), then goes out
    lights: t => t >= CUT0 ? clamp(1 - (t - CUT0) / 3, 0.05) : t > 176.3 ? 1 : litAt(t) ? 1 : 0.3,
    darkAt: t => t > 189 ? clamp((t - 189) / 3) * 0.6 : 0,
  };
}
